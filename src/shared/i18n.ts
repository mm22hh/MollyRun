let active: AppLocale = 'zh-CN'

export function setActiveLocale(locale: AppLocale): void {
  active = locale
}

export function activeLocale(): AppLocale {
  return active
}

export function resolveLocale(preference: LanguagePreference, systemTag: string): AppLocale {
  if (preference === 'zh-CN' || preference === 'en') return preference
  const tag = systemTag.toLowerCase().replace(/_/g, '-')
  return tag.startsWith('zh') ? 'zh-CN' : 'en'
}

export function translate(locale: AppLocale, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = (locale === 'en' ? en : zh)[key]
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = vars[name]
    return value === undefined ? '' : String(value)
  })
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  return translate(active, key, vars)
}

export function joinPhrases(parts: Array<string | false | null | undefined>): string {
  const text = parts.filter((part): part is string => Boolean(part))
  return active === 'en' ? text.join(' ') : text.join('')
}
